# POR QUÉ: Npgsql 10 lee las columnas `date` de PostgreSQL como DateOnly, no
# como DateTime. Los records del servicio que Dapper llena (ResumenGuardado,
# LotePendiente y otros) esperan DateTime, y el worker falla al buscar
# resúmenes de boletas y bajas. Npgsql 8.0.7 es la versión con la que el
# servicio funcionó siempre, y corre bien en .NET 10.
#
# CAMBIA UNA LÍNEA: Facturacion.Persistencia\Facturacion.Persistencia.csproj
# Copia .bak. Si el texto no está tal cual, NO TOCA NADA. No pregunta nada.
